/** An SVG path for every landmass in the overlay's projection (x = lon + 180, y = 90 − lat). */
export function landPath(): string {
  return LANDMASSES.map((ring) => {
    let d = '';
    for (let i = 0; i < ring.length; i += 2) {
      d += `${i ? 'L' : 'M'}${ring[i]! + 180} ${90 - ring[i + 1]!}`;
    }
    return `${d}Z`;
  }).join('');
}
