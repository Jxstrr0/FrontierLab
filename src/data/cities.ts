// Cities (docs/CONTENT.md §2). Index values are relative to 1.00 (Toronto-like).
import type { CountryId } from './types';

export type CitySize = 'S' | 'M' | 'L' | 'XL';
export type Difficulty = 'easy' | 'normal' | 'hard' | 'expert';

export interface CitySpec {
  id: string;
  name: string;
  country: CountryId;
  size: CitySize;
  tiles: number;
  lat: number;
  lon: number;
  rentIndex: number;
  wageIndex: number;
  incomeIndex: number;
  costIndex: number;
  /** A0 in SIMULATION §9.3: the city's big banks that aren't drawn on the map. */
  incumbent: number;
  rivals: number;
  ink: string;
  inkName: string;
  start?: Difficulty;
  /**
   * How crowded the city is (default 1): scales every lot's foot traffic and
   * the city-wide customer pool (CITY_MARKET), so a dense city packs more
   * customers into each branch's catchment (CONTENT §2).
   */
  density?: number;
  /** Whether the city has a waterfront district. */
  water: boolean;
  /** The city's airport (CONTENT §2 airports); every map has one. */
  airport: { code: string; name: string };
  /**
   * Regional sites (CONTENT §2): a small map with an airport and 1–2 named
   * employers, and no storefronts, offices, rivals or other buildings.
   */
  regional?: { employers: { name: string; type: string }[] };
  /**
   * A new region (post-C8, SIMULATION §20a): closed to flights until
   * NEW_REGIONS.openWeek, never a start city, and the first sales office there
   * pays a market-entry licence by city size.
   */
  late?: true;
}

