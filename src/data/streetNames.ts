/** The street set for a city: its own, else its country's, else plain English. */
export function streetSetFor(cityId: string, country: CountryId | undefined): StreetSet {
  return (
    STREETS_BY_CITY[cityId] ??
    (country ? STREETS_BY_COUNTRY[country] : undefined) ?? {
      names: STREETS_BY_COUNTRY.CA.names,
      kinds: ENGLISH_KINDS,
    }
  );
}
